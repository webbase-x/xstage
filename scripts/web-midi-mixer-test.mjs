import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../web-midi-mixer.js',import.meta.url),'utf8');
const events=[];
class Event{constructor(type){this.type=type;}}
const scope={Event,dispatchEvent:event=>events.push(event.type)};
vm.runInNewContext(source,{window:scope,Event,console},{filename:'web-midi-mixer.js'});
const mixer=scope.XStageWebMidiMixer;
assert.equal(mixer.getGain(0),1);
assert.equal(mixer.isMuted(9),false);
mixer.setLevel(0,145);
assert.equal(mixer.getGain(0),1.45);
mixer.setLevel(0,999);
assert.equal(mixer.getGain(0),1.5,'Channel gain must be bounded');
mixer.setLevel(0,-100);
assert.equal(mixer.getGain(0),0);
mixer.setMute(0,true);
assert.equal(mixer.isMuted(0),true);
assert.equal(mixer.isMuted(1),false);
mixer.setMute(0,false);
mixer.setSolo(2,true);
assert.equal(mixer.isMuted(0),true,'Solo hides non-solo channels');
assert.equal(mixer.isMuted(2),false);
mixer.setSolo(9,true);
assert.equal(mixer.isMuted(9),false,'Drum channel can join a multi-solo');
mixer.resetForSong();
assert.equal(mixer.isMuted(0),false);
assert.equal(mixer.getGain(0),1);
assert.equal(mixer.getChannel(2).solo,false);
assert.equal(mixer.getGain(-1),1);
assert.equal(mixer.getChannel(16),null);
assert.ok(events.length>=7&&events.every(x=>x==='xstage-midi-mixerchange'));
const pro=fs.readFileSync(new URL('../midi-pro-engine.js',import.meta.url),'utf8');
const fallback=fs.readFileSync(new URL('../browser-midi.js',import.meta.url),'utf8');
const app=fs.readFileSync(new URL('../app.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../karaoke.html',import.meta.url),'utf8');
assert.ok(pro.includes("setSystemParameter?.('isMuted'"),'SpessaSynth channel mute must survive MIDI CC7');
assert.ok(pro.includes("setSystemParameter?.('gain'"),'SpessaSynth channel gain must be independent');
assert.ok(pro.includes("'gain',muted?0:mixer.getGain(ch)"),'Mute or Solo silences sustained notes immediately');
assert.ok(pro.includes('detachMixer();'),'SpessaSynth mixer listeners must be detached');
assert.ok(fallback.includes('gain.connect(mixerGains[n.channel]||master)'),'Web Audio notes route by channel');
assert.ok(fallback.includes("removeEventListener?.('xstage-midi-mixerchange'"),'Web Audio listener cleaned up');
assert.ok(app.includes('window.XStageWebMidiMixer?.resetForSong?.();'),'New MIDI songs reset old muting');
assert.ok(html.includes('web-midi-mixer.js?v=1127'),'Mixer loaded before song playback');
console.log('PASS: channel levels, mute/solo, song reset, real synth integration, cleanup');
